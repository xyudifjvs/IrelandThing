// Build-time extraction only. Never execute prototype scripts in the application.
import fs from "node:fs";
import postcss from "postcss";
const base = "design-reference/2026-11-weatherly/originals/";
const out = "apps/web/app/(portal)/portal/_components/";
const sources = {
  buyer: "Weatherly Buyer Intake.html",
  seller: "Weatherly Seller Intake.html",
  "buyer-compliance": "Weatherly Buyer Compliance Intake.html",
  "seller-compliance": "Weatherly Seller Compliance Intake.html",
};
const templates = {};
let css = "";
for (const [variant, file] of Object.entries(sources)) {
  const source = fs.readFileSync(base + file, "utf8");
  // Only the known static form. Preview scripts and all external resources are excluded.
  let markup = source.slice(
    source.indexOf('<div class="shell">'),
    source.indexOf("\n<script>"),
  );
  markup = markup
    .replace(/<!--[^]*?-->/g, "")
    .replace(/<p class="banner" data-show="(?:service|side)=[^]*?<\/p>/g, "");
  if (/<script|\son\w+=|javascript:/i.test(markup))
    throw Error("Unexpected active content in " + file);
  markup = markup.replace(
    "Submitting as <b>Sample Agent</b> · agent@brokerage.com",
    "Submitting as <b data-agent-name></b> · <span data-agent-email></span>",
  );
  markup = markup.replaceAll("<h1>", '<h1 tabindex="-1">');
  markup = markup.replace("<main>", '<main id="main-content" tabindex="-1">');
  markup = markup.replace('<h2>Transaction submitted</h2>','<h2>Received—awaiting Ireland’s review.</h2>');
  markup = markup.replace(
    'id="restart">Start over',
    'id="restart">Start another transaction',
  );
  markup = markup.replace(
    "In the live form this button opens your payment page in a new tab. Payment link to be added.",
    "Payment link to be added. Ireland must confirm the gift, price and payment terms before payment.",
  );
  templates[variant] = markup;
  if (!css) css = [...source.matchAll(/<style>([^]*?)<\/style>/g)].at(-1)[1];
}
const ast = postcss.parse(css);
ast.walkRules((rule) => {
  if (rule.parent.type === "atrule" && /keyframes$/.test(rule.parent.name))
    return;
  rule.selectors = rule.selectors.map((sel) =>
    [":root", "html", "body"].includes(sel.trim())
      ? ".weatherly-intake"
      : ".weatherly-intake " + sel,
  );
});
const fonts = fs
  .readFileSync("design-reference/2026-11-weatherly/intake-fonts.css", "utf8")
  .replace(
    /url\(https:[^)]*dmsans[^)]*\)/g,
    () =>
      `url('/fonts/intake-dm-sans-${[400, 500, 600][(globalThis.fontIndex = (globalThis.fontIndex ?? -1) + 1)]}.ttf')`,
  )
  .replace(
    /url\(https:[^)]*ebgaramond[^)]*\)/g,
    () =>
      `url('/fonts/intake-eb-garamond-${[400, 500][(globalThis.ebIndex = (globalThis.ebIndex ?? -1) + 1)]}.ttf')`,
  );
const reset =
  '.weatherly-intake {min-height:100vh;font:15px/1.5 "DM Sans",Arial,sans-serif;}\n.weatherly-intake p{margin-block:1em}.weatherly-intake h3{font-family:var(--body)}\n';
fs.writeFileSync(
  out + "reference-intake.css",
  fonts +
    reset +
    ast.toString() +
    `\n.weatherly-intake .proto button,.weatherly-intake .proto a,.weatherly-intake .proto select {font:inherit;color:inherit;background:transparent;border:0;padding:0;text-decoration:underline;cursor:pointer}.weatherly-intake .proto select{background:var(--ink);max-width:180px;min-height:0;width:auto}.weatherly-intake .draft-tools {padding:12px 16px;border-bottom:1px solid var(--line);background:var(--card)}.weatherly-intake .draft-tools button{margin:4px 12px 4px 0}.weatherly-intake .save-message {margin:0;padding:10px 16px;background:var(--note)}.weatherly-intake .doclist small{display:block}.weatherly-intake .review dd{white-space:pre-wrap}@media(max-width:760px){.weatherly-intake .shell{grid-template-columns:minmax(0,1fr)}.weatherly-intake .rail{position:static;height:auto;min-width:0}}\n`,
);
fs.writeFileSync(
  out + "reference-templates.ts",
  "// Generated by tools/design/generate-intake.mjs from preserved static reference markup.\nexport const referenceTemplates = " +
    JSON.stringify(templates, null, 2) +
    " as const;\nexport type ReferenceVariant = keyof typeof referenceTemplates;\n",
);
// The review formatting is the inspected presentation code, with all queries scoped
// to this form and file counts sourced exclusively from durable private documents.
let reviewCode =
  "// Generated from inspected presentation-only review functions. No prototype runtime.\n";
reviewCode +=
  'export function buildReferenceReview(root: HTMLElement, variant: string, files: Record<string,{name:string}[]>) {\nconst form=root.querySelector("form")!;\nconst val=(name:string):string=>{const el=form.elements.namedItem(name);if(!el)return "";if(el instanceof RadioNodeList)return el.value;const input=el as HTMLInputElement;return input.type==="checkbox"?(input.checked?"on":""):input.value;};\nconst v=(id:string)=>val(id).trim();\nconst esc=(s:unknown)=>String(s).replace(/[&<>\\"]/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",\\"\\": "&quot;"}[c]||c));\n';
// Use explicit helper text to keep the generated module strictly typed.
reviewCode =
  reviewCode.slice(0, reviewCode.indexOf("const esc=")) +
  `const esc=(s:unknown)=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]!));\nconst optText=(name:string)=>{const r=form.querySelector<HTMLInputElement>('input[name="'+name+'"]:checked');if(!r)return '';return r.closest('label')?.querySelector('.t')?.textContent?.trim()||r.value;};\nconst joinNz=(arr:string[],sep=' · ')=>arr.filter(Boolean).join(sep);\n`;
for (const [variant, file] of Object.entries(sources)) {
  const source = fs.readFileSync(base + file, "utf8");
  let body = source
    .split("function buildReview(){")[1]
    .split("\ndocument.getElementById('review').addEventListener")[0];
  body = body.slice(0, body.lastIndexOf("}"));
  body = body
    .replaceAll(
      "document.querySelectorAll(",
      "root.querySelectorAll<HTMLElement>(",
    )
    .replaceAll(
      "document.getElementById(",
      'root.querySelector<HTMLElement>("#"+',
    );
  body = body
    .replace("const rows=[]", "const rows: ([string,string,number]|null)[]=[]")
    .replace(
      "const add=(k,val,step)",
      "const add=(k:string,val:string,step:number)",
    )
    .replace("p.dataset.k", "p.dataset.k!");
  body = body.replace(
    "root.querySelector<HTMLElement>(\"#\"+'review').innerHTML",
    "root.querySelector<HTMLElement>('#review')!.innerHTML",
  );
  reviewCode += `if(variant===${JSON.stringify(variant)}){${body}\n}\n`;
}
reviewCode += "}\n";
fs.writeFileSync(out + "reference-review.ts", reviewCode);
console.log(
  "Extracted four inert templates, shared scoped CSS, and presentation-only review formatters.",
);
